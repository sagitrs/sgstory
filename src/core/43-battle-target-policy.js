/* core/43-battle-target-policy（`sgstory#1914` 增量 3/3）：**谁可以被选**。
 *
 * ## 为什么需要
 * 现码的 `targetOptions` 恒为「所有未出局者」（`40-battle.js:482` 的 `everyone.map(…)`）⇒
 * 玩家选伤害类动作时，候选里**第一个就是自己**（本席调试实测：凡选第一项即**打自己**，血直接归 0）。
 * 本件按**动作意图**给候选集：伤害类只列**敌方**，治疗类才列**己方**（含自己）。
 *
 * ## 形（纯函数，可单测）
 * - `阵营(攻击者, 全体)`：分出「己方／敌方」两组（按**同侧**判定：与攻击者同组者为己方）。
 * - `候选集({ 攻击者, 动作类, 己方, 敌方 })` ⇒ 数组（保持传入次序，✗ 重排 —— 次序是界面的事）。
 *
 * ## 动作类
 * `'damage'`（默认／未知一律按它：**窄**候选比**宽**候选安全 —— 宁可少列，✗ 让玩家自伤）、
 * `'heal'`（治疗类）、`'support'`（不指定目标，返回空集：调用方据此跳过选靶）。
 */
(() => {

	/** 动作类 → 取哪一侧。未知类按 `'damage'`（窄）。 */
	const 取侧 = (动作类) => (动作类 === 'heal' ? '己方' : 动作类 === 'support' ? '无' : '敌方');

	/**
	 * @param {object} o `{ 攻击者, 动作类, 己方, 敌方 }`
	 * @returns {Array} 候选单位（**同一数组内不重复**，保持各自序列原有次序）
	 */
	const 候选集 = ({ 攻击者, 动作类, 己方, 敌方 } = {}) => {
		const 侧 = 取侧(动作类);
		if (侧 === '无') return [];
		if (侧 === '敌方') return (敌方 ?? []).slice();
		/* 治疗类：己方全体（**含自己** —— 给自己上药是常见动作）。 */
		const 我 = 己方 ?? [];
		if (攻击者 != null && !我.includes(攻击者)) return [攻击者, ...我];
		return 我.slice();
	};

	/** 自检用：某候选集是否**不含**攻击者本人（伤害类应当如此）。 */
	const 含自己 = (集, 攻击者) => (集 ?? []).includes(攻击者);

	RPG.靶策略 = Object.freeze({ 候选集, 取侧, 含自己 });
})();

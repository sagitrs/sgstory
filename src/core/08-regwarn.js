/* RPG 核心 —— **注册面 id 冲突的收集器**（`sgstory#295` 乙 · 0.0.3）
 *
 * ## 为什么要有它
 *   一个故事同时装两套规则包（如 `dnd3` 与 `dnd-5e`）时，两包**共用一张 id 表**（`00-namespace.js` 明写）
 *   ⇒ 后装者**如实**遮蔽前者。此前**每处注册点各自** `console.warn` 一行 ⇒ 实测一次加载 **13 条**散装警告
 *   （`sgstory-books#288` 勘察）：读不下去，也看不出「一共几处、都是谁遮蔽谁」。
 *   ⇒ 本件把它们**收在一处**：注册点只**报**（✗ 打印），加载期结束**汇总印一次**（含**计数**与**逐条具名**）。
 *
 * ## 纪律（✗ 不做的两件事）
 *   · **✗ 不静默**：汇总仍**如实**印出（条数 ＋ 每条 `类「id」详情`）—— 静默会把**真实遮蔽**藏起来，
 *     而那正是引擎注释点名的「已知风险」；
 *   · **✗ 不在此判「该不该遮蔽」**：谁对谁错是**故事装配**的事 ⇒ 那是 `packs` 口（`#295` 甲）的活。
 *
 * ## 形
 *   `RPG.regWarn.报(类, id, 详情)` —— 注册点调它（**只收集**）；
 *   `RPG.regWarn.汇总({印})`       —— 取读数（`{条数, 条}`）并按需印；缺省印、**印过即不再印**（✗ 重复刷屏）；
 *   `RPG.regWarn.条数()` / `.清()` —— 读条数／清空（测试与判据用）。
 *   · **自动落点**：**首次** `报()` 之后挂一个 `setTimeout(…, 0)` ⇒ 同一 tick 内的同步注册都收完再印；
 *     ✗ 无冲突则**不挂**（安静）。
 *   · 汇总**只发一条 `console.warn`**（明细用 `\n` 折在同一条里 ⇒ 「恰一次」这类计数断言读得出）。
 *   ⚠ 能力缺席（无 `setTimeout` 的沙箱）⇒ ✗ 不自动印；判据可**手动**调 `汇总()`（同一条路径）。
 */
(() => {
	const 单 = [];
	let 已印 = false, 已挂 = false;

	/** 注册点调它：**只收集**（✗ 打印）。类＝「道具／角色／层表…」；详情＝原来那半句。 */
	const 报 = (类, id, 详情 = '将被覆盖') => {
		单.push({ 类: String(类), id: String(id), 详情: String(详情) });
		if (!已挂 && typeof setTimeout === 'function') {
			已挂 = true;
			setTimeout(() => 汇总(), 0);
		}
		return 单.length;
	};

	/** 汇总读数：`{条数, 条}`；`印` 缺省真 ⇒ **印一次**（已印过就不再印）。 */
	const 汇总 = ({ 印 = true } = {}) => {
		const 读数 = { 条数: 单.length, 条: 单.map((x) => ({ ...x })) };
		if (印 && 单.length && !已印) {
			已印 = true;
			const 明细 = 单.map((x) => `  · ${x.类}「${x.id}」${x.详情}`).join('\n');
			console.warn('[RPG] 本次共 ' + 单.length + ' 处 id 冲突（两包共用一张 id 表 ⇒ 后装者遮蔽前者）：\n' + 明细
				+ '\n  （谁遮蔽谁由**装载顺序**决定；单包故事不该撞这条 —— 见 `story.json` 的 `packs` 口。'
				+ '要按包取用具体实现时，直接用 `new DND3.Club()` 这种**包名限定**形，✗ 别经注册表查找。）');
		}
		return 读数;
	};

	RPG.regWarn = Object.freeze({
		报, 汇总,
		条数: () => 单.length,
		清: () => { 单.length = 0; 已印 = false; 已挂 = false; },
	});
})();
